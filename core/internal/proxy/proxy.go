// ContainerName is the container name of the OrbSleep-managed proxy.
const ContainerName = "orbsleep-lazy-tcp-proxy"

// Config is the dynamic configuration file format.
type Config struct {
	Services []ServiceConfig `yaml:"services" json:"services"`
}

// ServiceConfig is one proxy target.
type ServiceConfig struct {
	Name             string   `yaml:"name" json:"name"`
	Ports            []string `yaml:"ports,omitempty" json:"ports,omitempty"`
	IdleTimeoutSecs  int      `yaml:"idle_timeout_secs,omitempty" json:"idle_timeout_secs,omitempty"`
	StartTimeoutSecs int      `yaml:"start_timeout_secs,omitempty" json:"start_timeout_secs,omitempty"`
}

// Clone returns a deep copy: both the service slice and every Ports slice are
// independent, so callers can mutate a working copy without touching snapshots.
func (c Config) Clone() Config {
	out := Config{Services: make([]ServiceConfig, len(c.Services))}
	for i, s := range c.Services {
		out.Services[i] = s
		out.Services[i].Ports = append([]string(nil), s.Ports...)
	}
	return out
}

// Marshal renders the YAML config deterministically without mutating c.
func (c Config) Marshal() []byte {
	cp := c.Clone()
	sort.SliceStable(cp.Services, func(i, j int) bool { return cp.Services[i].Name < cp.Services[j].Name })
	var b bytes.Buffer
	b.WriteString("# Generated by OrbSleep Manager. Manual edits may be overwritten.\n")
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	_ = enc.Encode(cp)
	_ = enc.Close()
	return b.Bytes()
}

// Parse reads a config YAML file.
func Parse(raw []byte) (Config, error) {
	var c Config
	if len(bytes.TrimSpace(raw)) == 0 {
		return c, nil
	}
	if err := yaml.Unmarshal(raw, &c); err != nil {
		return c, err
	}
	return c, nil
}

// Service returns a deep copy of the config entry for a container name.
func (c Config) Service(name string) (ServiceConfig, bool) {
	for _, s := range c.Services {
		if s.Name == name {
			s.Ports = append([]string(nil), s.Ports...)
			return s, true
		}
	}
	return ServiceConfig{}, false
}

// Upsert replaces or appends a service entry. The stored entry never shares its
// Ports slice with the caller.
func (c *Config) Upsert(svc ServiceConfig) {
	svc = svc.clone()
	for i := range c.Services {
		if c.Services[i].Name == svc.Name {
			c.Services[i] = svc
			return
		}
	}
	c.Services = append(c.Services, svc)
}

// Remove drops a service entry. It always allocates a new slice so existing
// snapshots of the original config remain valid.
func (c *Config) Remove(name string) {
	out := make([]ServiceConfig, 0, len(c.Services))
	for _, s := range c.Services {
		if s.Name == name {
			continue
		}
		s.Ports = append([]string(nil), s.Ports...)
		out = append(out, s)
	}
	c.Services = out
}

func (s ServiceConfig) clone() ServiceConfig {
	s.Ports = append([]string(nil), s.Ports...)
	return s
}

// AdminClient talks to the proxy's admin API over loopback.
type AdminClient struct {
	BaseURL string
	APIKey  string
	HTTP    *http.Client
}

// NewAdminClient creates a client for a loopback admin endpoint.
func NewAdminClient(hostPort, apiKey string) *AdminClient {
	return &AdminClient{
		BaseURL: "http://" + hostPort,
		APIKey:  apiKey,
		HTTP:    &http.Client{Timeout: 20 * time.Second},
	}
}

// Ping verifies the admin API and key.
func (a *AdminClient) Ping(ctx context.Context) error {
	_, err := a.GetConfig(ctx)
	return err
}

// GetConfig reads the proxy's in-memory config.
func (a *AdminClient) GetConfig(ctx context.Context) (Config, error) {
	var out Config
	if err := a.do(ctx, http.MethodGet, "/config", nil, &out); err != nil {
		return out, err
	}
	return out, nil
}

// UpdateConfig writes a new config and applies it.
func (a *AdminClient) UpdateConfig(ctx context.Context, cfg Config) error {
	body := struct {
		Services []ServiceConfig `json:"services"`
	}{Services: cfg.Services}
	if body.Services == nil {
		body.Services = []ServiceConfig{}
	}
	var out struct {
		Status         string `json:"status"`
		ServicesLoaded int    `json:"services_loaded"`
		Error          string `json:"error"`
	}
	if err := a.do(ctx, http.MethodPut, "/config/update", body, &out); err != nil {
		return err
	}
	if out.Status != "ok" {
		return fmt.Errorf("代理拒绝配置: %s", out.Error)
	}
	return nil
}

// Reload asks the proxy to re-read its YAML file.
func (a *AdminClient) Reload(ctx context.Context) error {
	var out struct {
		Status string `json:"status"`
		Error  string `json:"error"`
	}
	if err := a.do(ctx, http.MethodGet, "/config/reload", nil, &out); err != nil {
		return err
	}
	if out.Status != "ok" {
		return fmt.Errorf("代理重新加载失败: %s", out.Error)
	}
	return nil
}

func (a *AdminClient) do(ctx context.Context, method, path string, body, out any) error {
	var reader io.Reader
	if body != nil {
		raw, err := json.Marshal(body)
		if err != nil {
			return err
		}
		reader = bytes.NewReader(raw)
	}
	req, err := http.NewRequestWithContext(ctx, method, a.BaseURL+path, reader)
	if err != nil {
		return err
	}
	req.Header.Set("X-API-Key", a.APIKey)
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	resp, err := a.HTTP.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	raw, _ := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if resp.StatusCode >= 400 {
		return fmt.Errorf("代理管理 API %s %s 返回 %d: %s", method, path, resp.StatusCode, strings.TrimSpace(string(raw)))
	}
	if out != nil {
		if err := json.Unmarshal(raw, out); err != nil {
			return fmt.Errorf("解析代理响应失败: %w", err)
		}
	}
	return nil
}

// ServiceSnapshot is one entry from the proxy /metrics endpoint.
type ServiceSnapshot struct {
	ContainerID      string `json:"container_id"`
	ContainerName    string `json:"container_name"`
	ListenPort       int    `json:"listen_port"`
	TargetPort       int    `json:"target_port"`
	Running          bool   `json:"running"`
	ContainerMissing bool   `json:"container_missing"`
	ActiveConns      int    `json:"active_conns"`
	LastActive       string `json:"last_active"`
}

// Metrics is the proxy /status payload subset. (The /metrics endpoint only
// serves PostgreSQL activity metrics and is disabled without METRICS_POSTGRES_URL.)
type Metrics struct {
	Services []ServiceSnapshot `json:"services"`
}

// FetchMetrics reads the proxy web /status endpoint.
func FetchMetrics(ctx context.Context, hostPort string) (Metrics, error) {
	var m Metrics
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, "http://"+hostPort+"/status", nil)
	if err != nil {
		return m, err
	}
	client := &http.Client{Timeout: 10 * time.Second}
	resp, err := client.Do(req)
	if err != nil {
		return m, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		return m, fmt.Errorf("代理 /status 返回 %d", resp.StatusCode)
	}
	if err := json.NewDecoder(io.LimitReader(resp.Body, 4<<20)).Decode(&m); err != nil {
		return m, err
	}
	return m, nil
}

// ComposeFile renders the docker-compose.yml used to run the proxy container.
// The proxy's listen ports are published on loopback so the macOS gateway can
// reach them regardless of the container IP (and across container restarts).
func ComposeFile(cfg model.Settings, apiKey, configDir string) []byte {
	rangeSpec := fmt.Sprintf("127.0.0.1:%d-%d:%d-%d", cfg.ProxyPortStart, cfg.ProxyPortEnd, cfg.ProxyPortStart, cfg.ProxyPortEnd)
	tmpl := fmt.Sprintf(`# Generated by OrbSleep Manager. Do not edit by hand.
services:
  lazy-tcp-proxy:
    image: mountainpass/lazy-tcp-proxy@sha256:ed51f0b3e4be05fb9e2104c92c7315d0643df9e93ac24d9028d2b7a0cd073f39
    container_name: %s
    restart: unless-stopped
    environment:
      CONFIG_PATH: /config/config.yaml
      ADMIN_PORT: "8081"
      ADMIN_API_KEY: %q
      WEB_PORT: "8080"
      IDLE_TIMEOUT_SECS: "%d"
      START_TIMEOUT_SECS: "%d"
      POLL_INTERVAL_SECS: "5"
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - %q
    ports:
      - %q
      - "127.0.0.1:%d:8081"
      - "127.0.0.1:%d:8080"
`, ContainerName, apiKey, cfg.IdleTimeoutSecs, cfg.StartTimeoutSecs, configDir+":/config", rangeSpec,
		cfg.AdminPort, cfg.WebPort)
	return []byte(tmpl)
}

// APIKey returns the proxy admin key, generating and persisting one on first use.
// The key is stored in the macOS Keychain when available, with a 0600 file as a
// fallback (e.g. when running in a launchd context without Keychain access).
func APIKey(dataDir string) (string, error) {
	const service = "orbsleep-proxy-admin"
	const account = "orbsleep"
	if out, err := exec.Command("security", "find-generic-password", "-s", service, "-a", account, "-w").Output(); err == nil {
		if key := strings.TrimSpace(string(out)); key != "" {
			return key, nil
		}
	}
	// Fallback key file (used when the Keychain is unavailable, e.g. in some
	// launchd contexts). Read it before generating a new key so the running
	// proxy's key stays valid across daemon restarts.
	path := filepath.Join(dataDir, "proxy", "admin.key")
	if raw, err := os.ReadFile(path); err == nil {
		if existing := strings.TrimSpace(string(raw)); existing != "" {
			return existing, nil
		}
	}
	key, err := randomKey()
	if err != nil {
		return "", err
	}
	if err := exec.Command("security", "add-generic-password", "-U", "-s", service, "-a", account, "-w", key).Run(); err == nil {
		return key, nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return "", err
	}
	if err := os.WriteFile(path, []byte(key), 0o600); err != nil {
		return "", err
	}
	return key, nil
}

func randomKey() (string, error) {
	f, err := os.Open("/dev/urandom")
	if err != nil {
		return "", err
	}
	defer f.Close()
	buf := make([]byte, 24)
	if _, err := io.ReadFull(f, buf); err != nil {
		return "", err
	}
	const alphabet = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
	out := make([]byte, 32)
	for i := range out {
		out[i] = alphabet[int(buf[i%len(buf)])%len(alphabet)]
	}
	return string(out), nil
}

// PortFree reports whether a TCP port is bindable on the given host IP.
func PortFree(hostIP string, port int) bool {
	addr := net.JoinHostPort(hostIP, fmt.Sprintf("%d", port))
	ln, err := net.Listen("tcp", addr)
	if err != nil {
		return false
	}
	ln.Close()
	return true
}

// PickFreePort finds a free loopback port at or after start.
func PickFreePort(start int) (int, error) {
	for p := start; p < start+200 && p <= 65535; p++ {
		if PortFree("127.0.0.1", p) {
			return p, nil
		}
	}
	return 0, fmt.Errorf("找不到空闲的本地端口（从 %d 开始）", start)
}
